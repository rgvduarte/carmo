let lang = 'pt';
const listeners = new Set();
const original = new Map();
const originalAttr = new Map();

export function getLang() { return lang; }
export function t(key, ...args) {
  const v = (lang === 'en' ? EN_JS[key] ?? EN[key] : PT_JS[key]) ?? PT_JS[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
export function pick(obj) { return typeof obj === 'string' ? obj : obj ? (obj[lang] ?? obj.pt) : ''; }
export function onLang(fn) { listeners.add(fn); }

// '21 fev. 2027' / '21 Feb 2027' (pt-PT's short month in Intl falls back to digits in some engines)
const PT_MON = ['jan.', 'fev.', 'mar.', 'abr.', 'mai.', 'jun.', 'jul.', 'ago.', 'set.', 'out.', 'nov.', 'dez.'];
const EN_MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
export function fmtDay(iso, { year = true, day = true } = {}) {
  const [y, m, d] = iso.split('-').map(Number);
  const mon = (lang === 'en' ? EN_MON : PT_MON)[m - 1];
  return [day && d ? d : null, mon, year ? y : null].filter((x) => x !== null).join(' ');
}

export function money(n) {
  return new Intl.NumberFormat(lang === 'en' ? 'en-IE' : 'pt-PT', { style: 'currency', currency: 'EUR', maximumFractionDigits: 0, useGrouping: 'always' }).format(n);
}
export function numFmt(n, d = 0) {
  return new Intl.NumberFormat(lang === 'en' ? 'en-GB' : 'pt-PT', { maximumFractionDigits: d, minimumFractionDigits: d, useGrouping: 'always' }).format(n);
}

export function setLang(next, { save = true } = {}) {
  lang = next === 'en' ? 'en' : 'pt';
  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-PT';
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const k = el.dataset.i18n;
    if (!original.has(el)) original.set(el, el.textContent);
    el.textContent = lang === 'en' && EN[k] ? EN[k] : original.get(el);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const k = el.dataset.i18nHtml;
    if (!original.has(el)) original.set(el, el.innerHTML);
    el.innerHTML = lang === 'en' && EN[k] ? EN[k] : original.get(el);
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    if (!originalAttr.has(el)) originalAttr.set(el, {});
    const store = originalAttr.get(el);
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, k] = pair.split(':');
      if (!(attr in store)) store[attr] = el.getAttribute(attr) || '';
      el.setAttribute(attr, lang === 'en' && EN[k] ? EN[k] : store[attr]);
    }
  });
  document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  if (save) {
    try { localStorage.setItem('gc.lang', lang); } catch (_) {}
    const u = new URL(location.href);
    if (u.searchParams.has('lang')) { u.searchParams.delete('lang'); history.replaceState(null, '', u.pathname + u.search + u.hash); }
  }
  listeners.forEach((fn) => fn(lang));
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('gc.lang'); } catch (_) {}
  const q = new URLSearchParams(location.search).get('lang');
  const guess = (navigator.language || 'pt').toLowerCase().startsWith('pt') ? 'pt' : 'en';
  const next = q || saved || guess;
  document.querySelectorAll('[data-lang]').forEach((b) => b.addEventListener('click', () => setLang(b.dataset.lang)));
  if (next !== 'pt') setLang(next, { save: false });
}
